#!/usr/bin/env bash
set -euo pipefail

backend_dir="$(cd "$(dirname "$0")/.." && pwd)"
source_dir="$backend_dir/../.runtime/hermes-source"
profile_dir="$backend_dir/../.runtime/hermes"
if [ ! -f "$profile_dir/.env" ] || [ ! -x "$source_dir/.hermes/bin/hermes" ]; then
  echo "Run setup_hermes.py and install_hermes.sh first. See server/README.md." >&2
  exit 1
fi
if [ "$(git -C "$source_dir" rev-parse HEAD)" != "$(cat "$backend_dir/hermes/revision.txt")" ]; then
  echo "Hermes version differs from the integration's pinned revision." >&2
  exit 1
fi

mkdir -p "$profile_dir/workspace"
python3 "$backend_dir/scripts/apply_hermes_profile.py"
# Avoid loading the upstream checkout's coding instructions as business context.
cd "$profile_dir/workspace"
export HERMES_HOME="$profile_dir"
# Use the launcher generated by Hermes PM; current Hermes stores dependencies
# in managed environments rather than a checkout-local .venv.
exec "$source_dir/.hermes/bin/hermes" gateway run "$@"
